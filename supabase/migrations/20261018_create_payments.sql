create table if not exists public.payments (
  payment_id bigint generated by default as identity primary key,
  booking_id bigint not null references public.bookings (bookingid) on delete cascade,
  customer_id uuid not null references public."User" (id) on delete cascade,
  payment_status text not null default 'pending'
    check (payment_status in ('pending', 'complete', 'failed', 'cancelled')),
  paid_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  constraint payments_booking_id_key unique (booking_id)
);

alter table public.payments enable row level security;

grant select on table public.payments to authenticated;

drop policy if exists "Customers can read their own payments" on public.payments;

create policy "Customers can read their own payments"
on public.payments
for select
to authenticated
using (customer_id = auth.uid());
